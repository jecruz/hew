#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const os = require('os');

// ── Colors ──────────────────────────────────────────
const c = { cyan: '\x1b[36m', green: '\x1b[32m', yellow: '\x1b[33m', red: '\x1b[31m', bold: '\x1b[1m', dim: '\x1b[2m', reset: '\x1b[0m' };

// ── Runtime skill directories ──────────────────────
const RUNTIME_DIRS = {
  claude:  { global: '~/.claude/skills/hew',       local: '.claude/skills/hew' },
  codex:   { global: '~/.codex/skills/hew',        local: '.agents/skills/hew' },
  pi:      { global: '~/.pi/agent/extensions',     local: '.pi/agent/extensions' },
  hermes:  { global: '~/.hermes/skills/hew',       local: '.hermes/skills/hew' },
};
const ALL_RUNTIMES = Object.keys(RUNTIME_DIRS);

// ── Args ───────────────────────────────────────────
const args = process.argv.slice(2);
const flags = {
  global: args.includes('--global') || args.includes('-g'),
  local:  args.includes('--local')  || args.includes('-l'),
  all:    args.includes('--all'),
  uninstall: args.includes('--uninstall') || args.includes('-u'),
};
const selected = ALL_RUNTIMES.filter(r => args.includes(`--${r}`));

if (flags.all) selected.push(...ALL_RUNTIMES);
if (selected.length === 0 && !flags.uninstall) selected.push('claude'); // default

if (!flags.global && !flags.local && !flags.uninstall) flags.global = true; // default

// ── Helpers ────────────────────────────────────────
function home(p) { return p.replace(/^~/, os.homedir()); }
function skillSource() { return path.join(__dirname, '..', 'SKILL.md'); }
function log(icon, msg) { console.log(`  ${icon} ${msg}`); }

// ── Install: Claude ───────────────────────────────
function installClaude(targetDir) {
  const dest = path.join(targetDir, 'SKILL.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(skillSource(), dest);
  log('✓', `Claude → ${c.dim}${dest}${c.reset}`);
}

// ── Install: Codex ────────────────────────────────
function installCodex(targetDir) {
  const dest = path.join(targetDir, 'SKILL.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(skillSource(), dest);
  log('✓', `Codex → ${c.dim}${dest}${c.reset}`);
}

// ── Install: Pi (convert SKILL.md to Pi extension) ─
function installPi(targetDir) {
  const skillMd = fs.readFileSync(skillSource(), 'utf8');

  // Extract frontmatter
  const fmMatch = skillMd.match(/^---\n([\s\S]*?)\n---/);
  let name = 'hew', description = '';
  if (fmMatch) {
    const fm = fmMatch[1];
    const nameMatch = fm.match(/name:\s*(.+)/);
    const descMatch = fm.match(/description:\s*(.+)/);
    if (nameMatch) name = nameMatch[1].trim();
    if (descMatch) description = descMatch[1].trim();
  }

  const piExt = `/**
 * ${name} — ${description}
 * Auto-generated by hew-install
 */

import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

export default function (pi: ExtensionAPI) {
  pi.registerCommand("${name}", {
    description: "${description.replace(/"/g, '\\"')}",
    handler: async (args, ctx) => {
      return {
        content: [{
          type: "text",
          text: \`Follow the Hew workflow:\\n\\n\${fs.readFileSync(process.env.HEW_SKILL_PATH || '${skillSource().replace(/'/g, "\\'")}', 'utf8')}\`
        }],
        details: {}
      };
    },
  });

  pi.on("before_agent_start", async (event) => {
    const skill = fs.readFileSync(process.env.HEW_SKILL_PATH || '${skillSource().replace(/'/g, "\\'")}', 'utf8');
    return { systemPrompt: event.systemPrompt + "\\n\\n---\\n**⚒ Hew Workflow Active**\\n\\n" + skill + "\\n---\\n" };
  });
}
`;

  const dest = path.join(targetDir, 'hew.js');
  fs.mkdirSync(targetDir, { recursive: true });
  fs.writeFileSync(dest, piExt, 'utf8');
  log('✓', `Pi → ${c.dim}${dest}${c.reset}`);
}

// ── Install: Hermes ────────────────────────────────
function installHermes(targetDir) {
  const dest = path.join(targetDir, 'SKILL.md');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(skillSource(), dest);
  log('✓', `Hermes → ${c.dim}${dest}${c.reset}`);
}

// ── Uninstall ──────────────────────────────────────
function uninstallRuntime(runtime, isGlobal) {
  const dirs = RUNTIME_DIRS[runtime];
  if (!dirs) return;
  const target = isGlobal ? home(dirs.global) : path.resolve(dirs.local);

  if (runtime === 'pi') {
    const file = path.join(target, 'hew.js');
    if (fs.existsSync(file)) { fs.unlinkSync(file); log('✗', `Pi: removed ${c.dim}${file}${c.reset}`); }
  } else {
    if (fs.existsSync(target)) { fs.rmSync(target, { recursive: true }); log('✗', `${runtime}: removed ${c.dim}${target}${c.reset}`); }
  }
}

// ── Install dispatch ───────────────────────────────
const installers = { claude: installClaude, codex: installCodex, pi: installPi, hermes: installHermes };

function installRuntime(runtime, isGlobal) {
  const dirs = RUNTIME_DIRS[runtime];
  if (!dirs) { log(c.yellow + '⚠', `Unknown runtime: ${runtime}` + c.reset); return; }
  const target = isGlobal ? home(dirs.global) : path.resolve(dirs.local);
  installers[runtime](target);
}

// ── Main ───────────────────────────────────────────
console.log(`\n  ${c.bold}⚒  Hew — Installer v${require('../package.json').version}${c.reset}\n`);

if (flags.uninstall) {
  for (const r of selected) uninstallRuntime(r, flags.global);
} else {
  const scope = flags.global ? 'global' : 'local';
  log(c.cyan + '●', `Installing for ${selected.join(', ')} (${scope})` + c.reset);
  for (const r of selected) installRuntime(r, flags.global);
}

console.log(`\n  ${c.green}Done.${c.reset} Activate with: ${c.bold}/hew questions "your task"${c.reset}\n`);
